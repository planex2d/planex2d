"""Writes src/python/planex/_planex.pyi, the type stub of the compiled module, from the signature lines its docstrings
start with, and, for the methods the Python modules attach to its classes, from their annotations.

    python tools/stubgen.py [out]     (with planex built and importable)
"""
import enum
import inspect
import re
import sys
from pathlib import Path

import planex
import planex._planex as module

OUT = Path(__file__).resolve().parents[1] / "src" / "python" / "planex" / "_planex.pyi"
SIGNATURE = re.compile(r"^(\w+)\((.*)\)(?: -> (.+))?$")
NAME = re.compile(r"[A-Za-z_][\w.]*")
# netgen's types the signature lines and annotations name without a module
NETGEN = {"TopoDS_Shape": "from netgen.occ import TopoDS_Shape", "Axes": "from netgen.occ import Axes",
          "IdentificationType": "from netgen.meshing import IdentificationType"}
KNOWN = {"Any", "Callable", "Iterator", "Self", "Sequence", "overload", "np", "occ", "enum", "Color", "Id", "Ids", "PlaneLike", "Point",
         "Point3", "None"} | set(dir(__builtins__))
imports = set()
HEADER = '''# SPDX-FileCopyrightText: 2026 Sebastian Hirnschall
# SPDX-License-Identifier: LGPL-2.1-or-later

# generated by tools/stubgen.py from the docstrings' signature lines; do not edit
from typing import Any, Callable, Iterator, Self, Sequence, overload

import numpy as np
from netgen import occ

from planex.types import Color, Id, Ids, Plane as PlaneLike, Point, Point3
'''


def SignatureLines(doc, name):
    """the forms of a call as its docstring writes them: (parameters, return) per line, until the first blank line"""
    forms = []
    for line in (doc or "").splitlines():
        m = SIGNATURE.match(line.strip())
        if not m or m.group(1) != name:
            break
        forms.append((m.group(2), m.group(3) or "None"))
    return forms


def SplitTop(text, sep=","):
    """text split at sep outside brackets"""
    parts, depth, start = [], 0, 0
    for i, c in enumerate(text):
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == sep and depth == 0:
            parts.append(text[start:i])
            start = i + 1
    parts.append(text[start:])
    return [p.strip() for p in parts if p.strip()]


def Parameter(p):
    """one parameter of a signature line as a stub writes it: a default becomes ..., the type name Plane the alias of
    what a call takes as a plane (the class Plane stays the return type)"""
    if p in ("/", "*"):
        return p
    name, _, default = p.partition("=")
    name = re.sub(r"\bPlane\b", "PlaneLike", name.strip())
    # a list parameter takes any sequence (pybind11 converts one); list[A | B] would not take a list[A]
    name = re.sub(r"\blist\[", "Sequence[", name)
    return f"{name} = ..." if default else name


def StubDef(name, params, ret, method, static, indent):
    """a def line: self first for a method"""
    ps = [Parameter(p) for p in SplitTop(params)]
    types = [p.partition(":")[2].partition("=")[0] for p in SplitTop(params)] + [ret]
    for n in NAME.findall(re.sub(r"'[^']*'|\"[^\"]*\"", "", " ".join(types))):
        head = n.split(".")[0]
        if n in NETGEN:
            imports.add(NETGEN[n])
        elif head not in KNOWN and not hasattr(module, head) and hasattr(planex, head):
            imports.add(f"from {getattr(planex, head).__module__} import {head}")
    if method and not static:
        ps.insert(0, "self")
    return f"{indent}def {name}({', '.join(ps)}) -> {ret}: ..."


def Annotation(f, ann):
    """an annotation as text; the names it uses that the stub does not know imported from where f finds them"""
    text = ann if isinstance(ann, str) else inspect.formatannotation(ann)
    for n in NAME.findall(re.sub(r"'[^']*'|\"[^\"]*\"", "", text)):
        head = n.split(".")[0]
        if head in KNOWN or hasattr(module, head):
            continue
        if head in NETGEN:
            imports.add(NETGEN[head])
            continue
        found = f.__globals__.get(head)
        if inspect.ismodule(found):
            imports.add(f"import {found.__name__}" + (f" as {head}" if found.__name__ != head else ""))
        elif found is not None:
            imports.add(f"from {found.__module__} import {head}")
    return text


def PythonDef(name, f, method, indent):
    """a def line from a Python function's own signature and annotations; attached to a class (method), its first
    parameter is the object"""
    try:
        sig = inspect.signature(f)
    except (TypeError, ValueError):
        return f"{indent}def {name}(self, *args: Any, **kwargs: Any) -> Any: ..."
    parts, starred = [], False
    for k, p in enumerate(sig.parameters.values()):
        ann = p.annotation
        text = p.name if ann is inspect.Parameter.empty or (method and k == 0) else f"{p.name}: {Annotation(f, ann)}"
        if p.kind is p.VAR_POSITIONAL:
            text, starred = "*" + text, True
        elif p.kind is p.VAR_KEYWORD:
            text = "**" + text
        elif p.kind is p.KEYWORD_ONLY and not starred:
            parts.append("*")
            starred = True
        if p.default is not inspect.Parameter.empty:
            text += " = ..."
        parts.append(text)
    if method and not parts:
        parts.insert(0, "self")
    ret = sig.return_annotation
    ret = "Any" if ret is inspect.Signature.empty else Annotation(f, ret)
    return f"{indent}def {name}({', '.join(parts)}) -> {ret}: ..."


# the protocol methods pybind11 writes no signature lines for
DUNDERS = {"__repr__": "(self) -> str", "__str__": "(self) -> str", "__len__": "(self) -> int", "__int__": "(self) -> int",
           "__index__": "(self) -> int", "__eq__": "(self, other: object) -> bool", "__ne__": "(self, other: object) -> bool",
           "__copy__": "(self) -> Self", "__deepcopy__": "(self, memo: dict) -> Self",
           "__array__": "(self, dtype: Any = ..., copy: bool | None = ...) -> np.ndarray"}


def Routine(name, value, method, indent, cls=None):
    """the stub lines of a function or method: one def per form, @overload when there are several; a constructor's
    lines carry its class's name (cls)"""
    static = isinstance(value, staticmethod)
    f = value.__func__ if static else value
    forms = SignatureLines(getattr(f, "__doc__", ""), cls if name == "__init__" else name)
    if name == "__init__":
        forms = [(params, "None") for params, _ in forms]
    prefix = [f"{indent}@staticmethod"] if static else []
    if not forms and method and name in DUNDERS:
        return [f"{indent}def {name}{DUNDERS[name]}: ..."]
    if not forms and name == "__init__" and Members(getattr(module, cls)):
        return [f"{indent}def __init__(self, value: int) -> None: ..."]
    if not forms:
        if inspect.isfunction(f):
            return prefix + [PythonDef(name, f, method and not static, indent)]
        self = "self, " if method and not static else ""
        return prefix + [f"{indent}def {name}({self}*args: Any, **kwargs: Any) -> Any: ..."]
    if len(forms) == 1:
        return prefix + [StubDef(name, *forms[0], method, static, indent)]
    lines = []
    for params, ret in forms:
        lines += prefix + [f"{indent}@overload", StubDef(name, params, ret, method, static, indent)]
    return lines


def PropertyType(key, value):
    """the type a property's docstring states on its first line, Any without one"""
    doc = (getattr(value, "__doc__", "") or "").lstrip()
    first = doc.splitlines()[0] if doc else ""
    if not first.startswith(key + ": "):
        getter = getattr(value, "fget", None)
        if inspect.isfunction(getter) and "return" in getattr(getter, "__annotations__", {}):
            return Annotation(getter, getter.__annotations__["return"])
        return "Any"
    typ = first[len(key) + 2:].strip()
    for n in NAME.findall(typ):
        head = n.split(".")[0]
        if head not in KNOWN and not hasattr(module, head) and hasattr(planex, head):
            imports.add(f"from {getattr(planex, head).__module__} import {head}")
    return typ


def Class(name, cls):
    bases = [b.__name__ for b in cls.__bases__ if b.__module__ in (module.__name__, "builtins") and b is not object]
    bases = bases or (["enum.Enum"] if Members(cls) else [])
    lines = [f"class {name}({', '.join(bases)}):" if bases else f"class {name}:"]
    for member in Members(cls):
        lines.append(f"    {member}: {name}")
    if Members(cls):
        lines += ["    @property", "    def name(self) -> str: ...", "    @property", "    def value(self) -> int: ..."]
    for key, value in vars(cls).items():
        if key in SKIP or key.startswith("_pybind11"):
            continue
        if Members(cls) and key in ("name", "value"):
            continue
        if type(value).__name__ == "pybind11_static_property":
            lines.append(f"    {key}: {PropertyType(key, value)}")
        elif isinstance(value, property):
            lines.append(f"    @property")
            lines.append(f"    def {key}(self) -> {PropertyType(key, value)}: ...")
            if getattr(value, "fset", None) is not None:
                lines.append(f"    @{key}.setter")
                lines.append(f"    def {key}(self, value: Any) -> None: ...")
        elif isinstance(value, staticmethod) or callable(value):
            lines += Routine(key, value, True, "    ", name)
    # a view iterates by __getitem__ and __len__; type checkers want __iter__
    if "__getitem__" in vars(cls) and "__len__" in vars(cls) and "__iter__" not in vars(cls):
        lines.append("    def __iter__(self) -> Iterator[Any]: ...")
    return lines if len(lines) > 1 else lines + ["    ..."]


def Members(cls):
    """the members of a pybind11 enum"""
    return list(getattr(cls, "__members__", {}).keys())


SKIP = {"__dict__", "__module__", "__doc__", "__weakref__", "__members__", "__entries", "__hash__", "__getstate__",
        "__setstate__", "__new__", "__init_subclass__", "__subclasshook__"}


def Stub():
    lines = []
    names = [n for n in vars(module) if not n.startswith("__")]
    for name in names:
        value = getattr(module, name)
        if inspect.isclass(value):
            lines += Class(name, value) + [""]
    for name in names:
        value = getattr(module, name)
        if inspect.isclass(value):
            continue
        if callable(value):
            lines += Routine(name, value, False, "") + [""]
        elif isinstance(getattr(type(value), "__members__", None), dict):
            lines.append(f"{name}: {type(value).__name__}")
        else:
            lines.append(f"{name}: {type(value).__name__}")
    head = [HEADER.rstrip(), "import enum", *sorted(imports), ""]
    return "\n".join(head + lines).rstrip() + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.write_text(Stub())
    print("wrote", out)
